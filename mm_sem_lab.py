def needleman(seq1,seq2,match,mismatch,gap):
  m = len(seq2)
  n = len(seq1)

  T = [[0]*(n+1) for i in range(m+1)]
  for i in range(n+1):
    T[0][i] = i*gap
  for j in range(m+1):
    T[j][0] = j*gap

  print(T)

  for i in range(1,m+1):
    for j in range(1,n+1):
      sigma = match if seq2[i-1]==seq1[j-1] else mismatch
      T[i][j] = max(
          T[i-1][j-1] + sigma,
          T[i-1][j] + gap,
          T[i][j-1] + gap
      )
  print(T)

  i,j = m,n
  al1,al2 = "",""
  while i>0 or j>0:
    if i>0 and j>0 and T[i][j] == T[i-1][j-1] + (match if seq1[j-1]==seq2[i-1] else mismatch):
      al1,al2 = seq1[j-1]+al1,seq2[i-1]+al2
      i-=1
      j-=1
    elif i>0 and T[i][j] == T[i-1][j]+gap:
      al1,al2 = "-"+al1,seq2[i-1]+al2
      i-=1
    else:
      al1,al2 = seq1[j-1]+al1,"-"+al2
      j-=1
  print(al1)
  print(al2)

