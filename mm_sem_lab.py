def generate(n,phi,theta,sigma=1,c=0):
  p = len(phi)
  q = len(theta)
  X = np.zeros(n)
  eps = np.random.normal(0,sigma,n)

  for t in range(max(p,q),n):
    ar = sum(phi[i]*X[t-i-1] for i in range(p))
    ma = sum(theta[j]*eps[t-j-1] for j in range(q))
    X[t] = c + ar +eps[t] +ma

  return X

def forecast(X,phi,theta,steps=20):
  p = len(phi)
  q = len(theta)
  n = len(X)
  eps = np.zeros(n+steps)
  forecast = np.zeros(n+steps)
  forecast[:n] = X

  for t in range(n,n+steps):
    ar = sum(phi[i]*forecast[t-i-1] for i in range(p))
    ma = sum(theta[j]*eps[t-j-1] for j in range(q))
    forecast[t] = ar + ma
  return forecast[n:]
