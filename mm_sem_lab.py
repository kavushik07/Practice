import pandas as pd
import matplotlib.pyplot as pyplot
import numpy as np

companies = ["RELIANCE","INFY","TCS","HDFCBANK"]
open_prices = pd.DataFrame()
close_prices = pd.DataFrame()

for c in companies:
  df = pd.read_csv(f"{c}.csv",parse_dates=["Date"])
  df.set_index("Date",inplace=True)
  open_prices[c] = df["Open"]
  close_prices[c] = df["Close"]

returns = (close_prices-open_prices)/open_prices
returns.dropna()

mu = returns.mean().values.reshape(-1,1)
print(mu)
cov_matrix = returns.cov().values
print(pd.DataFrame(cov_matrix).round(8))

weights = np.random.rand(500,len(companies))

weights = weights / weights.sum(axis=1)[:,None]

mu_v = weights @ mu
var_v = np.array([w @ cov_matrix @ w.T for w in weights])
sd_v = np.sqrt(var_v)

#min_variance

u = np.ones((len(companies),1))
c_inv = np.linalg.inv(cov_matrix)
w_opt = (c_inv @ u) / (u.T @ c_inv @ u)

mu_min = w_opt.T @ mu
var_min = w_opt.T @ cov_matrix @ w_opt
sd_min = np.sqrt(var_min)

print(mu_min)
print(sd_min)

plt.scatter(sd_v,mu_v,label="Random Portfolios")
plt.scatter(sd_min,mu_min,label="min portfolio")
plt.scatter(np.sqrt(np.diag(cov_matrix)),mu.flatten(),color="red",label="Individual Portfolio")
plt.legend()
plt.show()