def differences(series,d=1):
  differ = series.copy()
  for _ in range(d):
    differ = np.diff(differ)
  return differ

def arima_forecast(series,phi,theta,d=1,steps=20):
  p = len(phi)
  q = len(theta)
  diff = differences(series)
  n = len(diff)
  eps = np.zeros(n+steps)
  forecast = np.zeros(n+steps)
  forecast[:n] = diff

  for t in range(n,n+20):
    ar = sum(phi[i]*forecast[t-i-1] for i in range(p))
    ma = sum(theta[j]*eps[t-j-1] for j in range(q))
    forecast[t] = ar + ma

  forecast_vals = forecast[n:]
  arima_forecast = forecast_vals + series[-1]
  return arima_forecast

