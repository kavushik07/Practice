def arima(phi,theta,n,d,sigma=1,c=0):
  p = len(phi)
  q = len(theta)
  eps = np.random.normal(0,sigma,n)
  X = np.zeros(n)

  for t in range(max(p,q),n):
    ar = sum(phi[i]*X[t-i-1] for i in range(p))
    ma = sum(theta[j]*eps[t-j-1] for j in range(q))
    X[t] = c + ar + eps[t] + ma

  Y = X.copy()
  for _ in range(d):
    Y = np.cumsum(Y)

  return Y


